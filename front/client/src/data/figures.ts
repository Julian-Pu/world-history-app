export function getFigureById(id: string): HistoricalFigure | undefined {
  return FIGURES.find(f => f.id === id);
}

export function getFiguresByEra(eraId: string): HistoricalFigure[] {
  return FIGURES.filter(f => f.era === eraId);
}

export function getFiguresByRegion(regionId: string): HistoricalFigure[] {
  return FIGURES.filter(f => f.region === regionId);
}

export function searchFigures(keyword: string): HistoricalFigure[] {
  const kw = keyword.toLowerCase();
  return FIGURES.filter(f =>
    f.name.toLowerCase().includes(kw) ||
    f.id.toLowerCase().includes(kw)
  );
}
